#!/usr/bin/env python3
"""Figure 6 + README section 5h: parametric congestion model vs measured NYC DOT street speeds.
Reads the aggregated CSV (d,h,v,n), results/model_speed_profile.json and results/congestion_shape_validation_<borough>.json.
    python scripts/nyc_figure_and_section.py --csv ~/.../i4gi-tjb9.csv --borough Manhattan --start 2026-09-01 --end 2026-10-01
Idempotent; numbers in the README section are generated, not typed."""
import argparse, json, os, re
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument("--csv", required=True)
ap.add_argument("--borough", default="Manhattan")
ap.add_argument("--start", default="2026-09-01")
ap.add_argument("--end", default="2026-10-01")
a = ap.parse_args()

df = pd.read_csv(a.csv)
df.columns = [c.strip().lower() for c in df.columns]
df["d"] = pd.to_datetime(df["d"]); df["h"] = df["h"].astype(int); df["v"] = df["v"].astype(float)
df = df[df["d"].dt.dayofweek < 5]
M = df.pivot_table(index="d", columns="h", values="v").reindex(columns=range(24)).dropna(thresh=20)
M = M.apply(lambda r: r.fillna(r.mean()), axis=1)
mean, sd = M.mean(axis=0).values, M.std(axis=0).values
model = np.array(json.load(open(os.path.join(ROOT, "results", "model_speed_profile.json"))), float)
mn, mm = mean / mean.max(), model / model.max()
r_mean_curves = float(np.corrcoef(mean, model)[0, 1])
slow_meas, slow_model = float(mean.max() / mean.min()), float(model.max() / model.min())
hour_min, hour_max = int(np.argmin(mean)), int(np.argmax(mean))
vj = json.load(open(os.path.join(ROOT, "results", f"congestion_shape_validation_{a.borough}.json")))
pear, ci, spear, nwd = vj.get("pearson"), vj.get("pearson_ci95"), vj.get("spearman"), vj.get("n_weekdays", len(M))

plt.rcParams.update({"font.size": 9.5, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25, "legend.frameon": False})
fig, ax = plt.subplots(figsize=(7.4, 4.3))
x = np.arange(24)
ax.fill_between(x, (mean - sd) / mean.max(), (mean + sd) / mean.max(), color="#1f3a93", alpha=0.15, label="measured, +-1 sd across weekdays")
ax.plot(x, mn, color="#1f3a93", lw=2.4, marker="o", ms=4, label=f"measured weekday mean ({a.borough}, NYC DOT)")
ax.plot(x, mm, color="#c0392b", lw=2.2, ls="--", marker="s", ms=4, label="parametric model")
ax.set_xlabel("hour of day"); ax.set_ylabel("speed / maximum of the curve"); ax.set_xticks(range(0, 24, 2))
ax.set_title(f"Congestion model vs measured street speeds, {a.borough}: Pearson r = {pear:.2f}" if pear is not None else "Congestion model vs measured street speeds", loc="left", fontweight="bold", fontsize=10)
ax.legend(loc="lower left", fontsize=8.5)
os.makedirs(os.path.join(ROOT, "results", "figures"), exist_ok=True)
stem = os.path.join(ROOT, "results", "figures", f"fig6_nyc_shape_{a.borough.lower()}")
fig.savefig(stem + ".png", dpi=220, bbox_inches="tight", facecolor="white"); fig.savefig(stem + ".pdf", bbox_inches="tight")

sec = f"""## 5h. Congestion model vs measured street speeds ({a.borough})

Generated by `scripts/nyc_figure_and_section.py` from `results/congestion_shape_validation_{a.borough}.json` and the NYC DOT traffic-speed feed (dataset `i4gi-tjb9`, {a.start} to {a.end}, weekdays only).

| Borough | Weekdays | Pearson r (95% CI) | Spearman rho | Peak/off-peak slowdown, measured | Peak/off-peak slowdown, model | Slowest / fastest hour (measured) |
|---|---|---|---|---|---|---|
| {a.borough} | {nwd} | {pear:.2f} ({ci[0]:.2f} to {ci[1]:.2f}) | {spear:.2f} | {slow_meas:.2f}x | {slow_model:.2f}x | {hour_min}:00 / {hour_max}:00 |

![Model vs measured street speeds](results/figures/fig6_nyc_shape_{a.borough.lower()}.png)

The agreement is moderate, clearly lower than on the two freeway sensor networks (section 5b). One borough and one month are covered; this is a shape comparison, not a calibration of congestion severity.

---

"""
p = os.path.join(ROOT, "README.md")
s = open(p, encoding="utf-8").read()
s = re.sub(r"## 5h\. Congestion model vs measured street speeds.*?\n---\n\n", "", s, flags=re.S)
s = s.replace("## 6. Reproduce", sec + "## 6. Reproduce", 1)
open(p, "w", encoding="utf-8").write(s)
print(f"r(mean curves)={r_mean_curves:.3f}; tool pearson={pear}; slowdown measured {slow_meas:.2f}x vs model {slow_model:.2f}x; slowest {hour_min}h fastest {hour_max}h; wrote section 5h and {stem}.png")

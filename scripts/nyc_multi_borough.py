#!/usr/bin/env python3
"""Multi-borough comparison of the congestion model with measured NYC DOT street speeds -> Fig. 6 and README section 5h.
    python scripts/nyc_multi_borough.py                    # uses ~/data/nyc_<Borough>.csv for every borough found
Runs tools/validate_congestion_shape.py for each borough, then renders figure + generated README section (idempotent)."""
import argparse, json, os, re, subprocess, sys
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument("--boroughs", nargs="*", default=["Manhattan", "Brooklyn", "Queens", "Bronx"])
ap.add_argument("--dir", default="~/data")
ap.add_argument("--start", default="2026-09-01")
ap.add_argument("--end", default="2026-10-01")
a = ap.parse_args()
D = os.path.expanduser(a.dir)
model = np.array(json.load(open(os.path.join(ROOT, "results", "model_speed_profile.json"))), float)

found = {}
for b in a.boroughs:
    p = os.path.join(D, f"nyc_{b}.csv")
    if not os.path.exists(p) and b == "Manhattan":
        alt = "/mnt/c/Users/Admin/Downloads/i4gi-tjb9.csv"
        p = alt if os.path.exists(alt) else p
    if os.path.exists(p):
        found[b] = p
if not found:
    sys.exit("no borough CSVs found")

res = {}
for b, p in found.items():
    out = os.path.join(ROOT, "results", f"congestion_shape_validation_{b}.json")
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "validate_congestion_shape.py"), "--start", a.start, "--end", a.end,
                        "--borough", b, "--csv", p, "--model-json", os.path.join(ROOT, "results", "model_speed_profile.json"), "--out", out],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"[FAIL] {b}: {r.stderr[-300:]}"); continue
    v = json.load(open(out))
    df = pd.read_csv(p); df.columns = [c.strip().lower() for c in df.columns]
    df["d"] = pd.to_datetime(df["d"]); df["h"] = df["h"].astype(int); df["v"] = df["v"].astype(float)
    df = df[df["d"].dt.dayofweek < 5]
    M = df.pivot_table(index="d", columns="h", values="v").reindex(columns=range(24)).dropna(thresh=20)
    M = M.apply(lambda r_: r_.fillna(r_.mean()), axis=1)
    mean, sd = M.mean(axis=0).values, M.std(axis=0).values
    res[b] = dict(mean=mean, sd=sd, pear=v["pearson"], ci=v["pearson_ci95"], spear=v["spearman"], nwd=v.get("n_weekdays", len(M)),
                  slow=float(mean.max() / mean.min()), hmin=int(np.argmin(mean)), hmax=int(np.argmax(mean)))
    print(f"[ok] {b}: r={v['pearson']:.3f}, slowdown {res[b]['slow']:.2f}x")
if not res:
    sys.exit("no borough succeeded")

slow_model = float(model.max() / model.min())
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25, "legend.frameon": False})
n = len(res); ncol = 2 if n > 1 else 1; nrow = int(np.ceil(n / ncol))
fig, axes = plt.subplots(nrow, ncol, figsize=(5.6 * ncol, 3.6 * nrow), squeeze=False)
for ax in axes.ravel():
    ax.axis("off")
x = np.arange(24)
for ax, (b, r) in zip(axes.ravel(), res.items()):
    ax.axis("on")
    ax.fill_between(x, (r["mean"] - r["sd"]) / r["mean"].max(), (r["mean"] + r["sd"]) / r["mean"].max(), color="#1f3a93", alpha=0.15)
    ax.plot(x, r["mean"] / r["mean"].max(), color="#1f3a93", lw=2.2, marker="o", ms=3.5, label="measured (NYC DOT, weekdays)")
    ax.plot(x, model / model.max(), color="#c0392b", lw=2, ls="--", marker="s", ms=3.5, label="parametric model")
    ax.set_title(f"{b}: r = {r['pear']:.2f}, slowdown {r['slow']:.2f}x vs {slow_model:.2f}x", loc="left", fontweight="bold", fontsize=9.5)
    ax.set_xticks(range(0, 24, 4)); ax.set_xlabel("hour of day"); ax.set_ylabel("speed / max")
first = next(ax for ax in axes.ravel() if ax.axison)
first.legend(loc="lower left", fontsize=8)
os.makedirs(os.path.join(ROOT, "results", "figures"), exist_ok=True)
stem = os.path.join(ROOT, "results", "figures", "fig6_nyc_shape")
fig.tight_layout(); fig.savefig(stem + ".png", dpi=220, facecolor="white"); fig.savefig(stem + ".pdf")

rows = "".join(f"| {b} | {r['nwd']} | {r['pear']:.2f} ({r['ci'][0]:.2f} to {r['ci'][1]:.2f}) | {r['spear']:.2f} | {r['slow']:.2f}x | {r['hmin']}:00 / {r['hmax']}:00 |\n" for b, r in res.items())
sec = f"""## 5h. Congestion model vs measured street speeds (NYC)

Generated by `scripts/nyc_multi_borough.py` from the NYC DOT traffic-speed feed (dataset `i4gi-tjb9`, {a.start} to {a.end}, weekdays only) and `results/congestion_shape_validation_<borough>.json`. The model's peak/off-peak slowdown for its representative edge is {slow_model:.2f}x.

| Borough | Weekdays | Pearson r (95% CI) | Spearman rho | Measured peak/off-peak slowdown | Slowest / fastest hour |
|---|---|---|---|---|---|
{rows}
![Model vs measured street speeds](results/figures/fig6_nyc_shape.png)

This is a shape comparison for one month; it is not a calibration of congestion severity (see section 5i for sensitivity to severity).

---

"""
p = os.path.join(ROOT, "README.md")
s = open(p, encoding="utf-8").read()
s = re.sub(r"## 5h\. Congestion model vs measured street speeds.*?\n---\n\n", "", s, flags=re.S)
s = s.replace("## 6. Reproduce", sec + "## 6. Reproduce", 1)
open(p, "w", encoding="utf-8").write(s)
print("section 5h and figure written for:", ", ".join(res))

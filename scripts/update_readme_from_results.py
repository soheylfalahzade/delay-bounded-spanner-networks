#!/usr/bin/env python3
"""Regenerate result-dependent README statements from the result files (no hand-copied numbers).

  * limitations bullets about the evaluation scale and the OD-dilation advantage  <- results/crosscity_table.md, results/spanner_report.json
  * section 5g (3.5 km runs)                                                      <- results/benchmarks/large_scale_<dist>m.csv
Idempotent.   python scripts/update_readme_from_results.py --od 30 30 5 [--dist 3500]
"""
import argparse, json, os, re, sys
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument("--od", type=int, nargs=3, default=[30, 30, 5], metavar=("SOURCES", "TARGETS", "REPEATS"))
ap.add_argument("--dist", type=int, default=3500)
a = ap.parse_args()
readme = os.path.join(ROOT, "README.md")
s = open(readme, encoding="utf-8").read()
lines = s.split("\n")

# ---- cross-city advantage statement ---------------------------------------------------------
tab = [l for l in open(os.path.join(ROOT, "results", "crosscity_table.md"), encoding="utf-8").read().split("\n") if l.startswith("|")]
hdr = [c.strip() for c in tab[0].strip("|").split("|")]
ia, ic = hdr.index("Advantage (x)"), hdr.index("City")
rows = [[c.strip() for c in l.strip("|").split("|")] for l in tab[2:]]
adv = {r[ic]: float(r[ia]) for r in rows}
below = sorted([c for c, v in adv.items() if v < 1.0], key=lambda c: adv[c])
n = len(adv)
p = None
rp = os.path.join(ROOT, "results", "spanner_report.json")
if os.path.exists(rp):
    p = json.load(open(rp)).get("cross_city", {}).get("city_level_significance", {}).get("p_value")
S, T, R = a.od
od_line = (f"- On OD-pair dilation ({n} cities; {S} sources x {T} targets x {R} repeats per city) the matched-density betweenness control has a larger worst-OD dilation "
           f"than the construction in {n - len(below)} of {n} cities (advantage ratio above 1)"
           + (f"; the ratio is below 1 in {', '.join(f'{c} ({adv[c]:.2f})' for c in below)}" if below else "")
           + (f"; the city-level test in the report gives p = {p:.4g}" if p is not None else "")
           + " (`results/crosscity_table.md`). The guarantee is the certificate; this comparison is secondary and depends on the choice of the matched control.")
scale_line = (f"- Evaluation scale: the twelve-city table uses city cores of about 1.5 km radius with {S} x {T} OD pairs and {R} repeats per city; "
              f"larger-radius runs on three cities are reported in section 5g.")
for i, l in enumerate(lines):
    if l.startswith("- On OD-pair dilation"):
        lines[i] = od_line
    if l.startswith("- Evaluation scale:"):
        lines[i] = scale_line
s = "\n".join(lines)

# ---- section 5g -------------------------------------------------------------------------------
csvp = os.path.join(ROOT, "results", "benchmarks", f"large_scale_{a.dist}m.csv")
if os.path.exists(csvp):
    d = pd.read_csv(csvp)
    d = d[d.real_osm == True]  # noqa: E712
    if len(d):
        head = ("| City | Nodes | Edges | t | Delay-bounded kept (%) | Forced lower bound (%) | Static free-flow kept (%) | Static free-flow certified | Union of per-hour greedy kept (%) |\n"
                "|---|---|---|---|---|---|---|---|---|\n")
        body = ""
        for r in d.itertuples():
            un = "" if pd.isna(r.union_retention_pct) else f"{r.union_retention_pct:.1f}"
            body += (f"| {r.city} | {r.nodes} | {r.edges} | {r.t:g} | {r.delay_bounded_retention_pct:.1f} | {r.forced_lower_bound_pct:.1f} | "
                     f"{r.static_ff_retention_pct:.1f} | {'yes' if r.static_ff_certified else 'no'} | {un} |\n")
        sec = (f"## 5g. Larger radius ({a.dist / 1000:g} km)\n\nGenerated by `scripts/update_readme_from_results.py` from `results/benchmarks/large_scale_{a.dist}m.csv` "
               f"(`python benchmarks/large_scale_run.py --dist {a.dist}`). Real OpenStreetMap networks only; the delay-bounded spanner is certified in every row.\n\n"
               + head + body + "\n---\n\n")
        s = re.sub(r"## 5g\. Larger radius.*?\n---\n\n", "", s, flags=re.S)
        s = s.replace("## 6. Reproduce", sec + "## 6. Reproduce", 1)
open(readme, "w", encoding="utf-8").write(s)

# ---- audit table status ---------------------------------------------------------------------------
ap_ = os.path.join(ROOT, "docs", "REFEREE_AUDIT.md")
if os.path.exists(ap_):
    t = open(ap_, encoding="utf-8").read()
    t = t.replace("**fixed (claim)** in limitations; do not state superiority on OD dilation.",
                  f"**re-measured**: with {S} x {T} x {R} OD pairs the ratio is above 1 in {n - len(below)} of {n} cities; README regenerated from the results.")
    t = t.replace("**open**: rerun with `--city-sources 30` and more repeats for the submission run.",
                  f"**fixed**: rerun with {S} x {T} x {R}; README regenerated from the results.")
    open(ap_, "w", encoding="utf-8").write(t)
print(f"advantage > 1 in {n - len(below)}/{n}; below 1: {below}; p = {p}; 5g {'written' if os.path.exists(csvp) else 'skipped (no CSV)'}")

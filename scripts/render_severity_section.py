#!/usr/bin/env python3
"""README section 5i (sensitivity to congestion severity), generated from results/benchmarks/severity_sensitivity.csv. Idempotent."""
import os, re
import pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = pd.read_csv(os.path.join(ROOT, "results", "benchmarks", "severity_sensitivity.csv"))
cities = sorted(d.city.unique())
g = d.groupby(["k", "t"]).agg(slow=("mean_edge_slowdown", "mean"), ours=("delay_bounded_retention_pct", "mean"),
                              forced=("forced_lower_bound_pct", "mean"), sff=("static_ff_retention_pct", "mean"),
                              sff_bad=("static_ff_certified", lambda x: int((~x).sum())),
                              sff_viol=("static_ff_violating_edges", "mean"),
                              cert=("delay_bounded_certified", "all")).reset_index()
head = ("| Severity factor k | Mean per-edge max/min travel-time ratio | t | Delay-bounded kept (%) | Forced lower bound (%) | Static free-flow kept (%) | "
        "Static free-flow uncertified (cities) | Mean violating edges, static free-flow | Delay-bounded certified in all cities |\n|---|---|---|---|---|---|---|---|---|\n")
body = "".join(f"| {r.k:g} | {r.slow:.2f} | {r.t:g} | {r.ours:.1f} | {r.forced:.1f} | {r.sff:.1f} | {r.sff_bad} of {len(cities)} | {r.sff_viol:.0f} | {'yes' if r.cert else 'NO'} |\n"
               for r in g.itertuples())
sec = (f"## 5i. Sensitivity to congestion severity\n\nGenerated by `scripts/render_severity_section.py` from `results/benchmarks/severity_sensitivity.csv` "
       f"(`python benchmarks/severity_sensitivity.py`; cities: {', '.join(cities)}). The excess delay of every edge is rescaled, "
       f"tt_k(h) = tt_ff (1 + k (tt(h)/tt_ff - 1)); k = 1 is the original model. Measured peak/off-peak slowdowns are 1.34-1.38x on freeways and 2.07x on Manhattan streets "
       f"against 1.50x for the model's representative edge; k = 2.14 reproduces the Manhattan slowdown for that edge.\n\n" + head + body +
       "\nMeans are over the listed cities. The static free-flow baseline does not depend on k (it ignores congestion), so its retention is constant while its violations are measured against the rescaled profile.\n\n---\n\n")
p = os.path.join(ROOT, "README.md")
s = open(p, encoding="utf-8").read()
s = re.sub(r"## 5i\. Sensitivity to congestion severity.*?\n---\n\n", "", s, flags=re.S)
s = s.replace("## 6. Reproduce", sec + "## 6. Reproduce", 1)
open(p, "w", encoding="utf-8").write(s)
print("section 5i written;", len(g), "rows")
